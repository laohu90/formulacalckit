/**
 * Intelligent Dynamic Subdomain Knowledge Base & Semantic Resolver
 * Guarantees zero pollution from Cloudflare Worker dummy placeholders,
 * preserves rich authentic Chinese titles and descriptions,
 * cleans mathematical formulas, and provides seamless tools.php integration.
 */
export function resolveDynamicToolMetadata(
  site: WorkerSubsiteTool,
  lang: 'en' | 'zh'
): ResolvedToolMetadata {
  const rawSub = (site.subdomain || '').toLowerCase().trim();
  const slug = rawSub.replace(/\.formulacalckit\.com$/, '').replace(/^https?:\/\//, '').trim();

  // Determine if incoming fields are dummy worker placeholders
  const isDummyTitle = isWorkerDummyTitle(site.title, slug);
  const isDummyDesc = isWorkerDummyDesc(site.desc);
  const isDummyCategory = isWorkerDummyCategory(site.category);
  const isDummyIcon = isWorkerDummyIcon(site.icon);

  // Preserve authentic user custom metadata (e.g. from tools.php HTML <title> and <meta>)
  const customTitle = (!isDummyTitle && site.title && site.title.trim().length > 0) ? site.title.trim() : null;
  const customDesc = (!isDummyDesc && site.desc && site.desc.trim().length > 5) ? site.desc.trim() : null;
  const customCategory = (!isDummyCategory && site.category && site.category.trim().length > 0) ? site.category.trim() : null;
  const customIcon = (!isDummyIcon && site.icon && site.icon.trim().length > 0) ? site.icon.trim() : null;

  // ----------------------------------------------------
  // TIER 1: Exact Registry Match (Highest Precision)
  // ----------------------------------------------------
  if (EXACT_TOOL_REGISTRY[slug]) {
    const item = EXACT_TOOL_REGISTRY[slug];
    const formulaRaw = site.formula && site.formula.trim().length > 0 && !site.formula.includes('\\rho')
      ? site.formula
      : item.formula;

    return {
      title: customTitle || (lang === 'zh' ? item.titleZh : item.titleEn),
      formula: formatFormulaDisplay(formulaRaw),
      category: customCategory || (lang === 'zh' ? item.categoryZh : item.categoryEn),
      desc: customDesc || (lang === 'zh' ? item.descZh : item.descEn),
      icon: customIcon || item.icon,
      quickSolverId: item.quickSolverId,
      tags: item.tags,
    };
  }

  // ----------------------------------------------------
  // TIER 2: Specificity-Ranked Rule Matching
  // ----------------------------------------------------
  for (const rule of SPECIFICITY_RULES) {
    if (rule.test(slug)) {
      const meta = rule.metadata(lang);
      const formulaRaw = site.formula && site.formula.trim().length > 0 ? site.formula : meta.formula;
      return {
        ...meta,
        title: customTitle || meta.title,
        desc: customDesc || meta.desc,
        formula: formatFormulaDisplay(formulaRaw),
        category: customCategory || meta.category,
        icon: customIcon || meta.icon,
      };
    }
  }

  // ----------------------------------------------------
  // TIER 3: Intelligent Semantic Fallback for Future Subdomains & tools.php
  // ----------------------------------------------------
  const combinedContext = `${slug} ${customTitle || ''} ${customDesc || ''}`.toLowerCase();

  const rawTokens = slug.split(/[-_]+/).filter(Boolean);
  const cleanTokens = rawTokens.filter(
    (t) => !['calculator', 'solver', 'tool', 'tools', 'online', 'kit', 'app', 'calc'].includes(t)
  );
  const translatedZhTokens: string[] = [];
  const capitalizedEnTokens: string[] = [];
  for (const token of cleanTokens) {
    capitalizedEnTokens.push(token.charAt(0).toUpperCase() + token.slice(1));
    if (MATH_TERM_DICTIONARY[token]) {
      translatedZhTokens.push(MATH_TERM_DICTIONARY[token].zh);
    }
  }

  let inferredCategoryZh = '实用与在线工具';
  let inferredCategoryEn = 'Utility & Tools';
  let inferredFormula = '';
  let inferredIcon = '🌐';

  if (
    combinedContext.includes('rest') ||
    combinedContext.includes('stop') ||
    combinedContext.includes('map') ||
    combinedContext.includes('nav') ||
    combinedContext.includes('traffic') ||
    combinedContext.includes('road') ||
    combinedContext.includes('highway') ||
    combinedContext.includes('休息区') ||
    combinedContext.includes('服务站') ||
    combinedContext.includes('公路') ||
    combinedContext.includes('停车') ||
    combinedContext.includes('房车') ||
    combinedContext.includes('导航')
  ) {
    inferredCategoryZh = '路线与便民导航';
    inferredCategoryEn = 'Navigation & Transit';
    inferredIcon = '🚗';
  } else if (
    combinedContext.includes('geo') ||
    combinedContext.includes('triangle') ||
    combinedContext.includes('polygon') ||
    combinedContext.includes('circle') ||
    combinedContext.includes('area') ||
    combinedContext.includes('perimeter') ||
    combinedContext.includes('几何') ||
    combinedContext.includes('面积') ||
    combinedContext.includes('周长')
  ) {
    inferredCategoryZh = '几何与图形';
    inferredCategoryEn = 'Geometry';
    inferredFormula = 'A = f(r, l, w)';
    inferredIcon = '📐';
  } else if (
    combinedContext.includes('phys') ||
    combinedContext.includes('force') ||
    combinedContext.includes('speed') ||
    combinedContext.includes('motion') ||
    combinedContext.includes('energy') ||
    combinedContext.includes('watt') ||
    combinedContext.includes('volt') ||
    combinedContext.includes('物理') ||
    combinedContext.includes('力学') ||
    combinedContext.includes('电路')
  ) {
    inferredCategoryZh = '物理与工程';
    inferredCategoryEn = 'Physics';
    inferredFormula = 'E = mc², F = ma';
    inferredIcon = '⚡';
  } else if (
    combinedContext.includes('fin') ||
    combinedContext.includes('money') ||
    combinedContext.includes('tax') ||
    combinedContext.includes('loan') ||
    combinedContext.includes('interest') ||
    combinedContext.includes('profit') ||
    combinedContext.includes('price') ||
    combinedContext.includes('金融') ||
    combinedContext.includes('理财') ||
    combinedContext.includes('利息')
  ) {
    inferredCategoryZh = '实用与金融';
    inferredCategoryEn = 'Finance';
    inferredFormula = 'FV = PV(1 + r)ᵗ';
    inferredIcon = '💰';
  } else if (
    combinedContext.includes('alg') ||
    combinedContext.includes('equation') ||
    combinedContext.includes('matrix') ||
    combinedContext.includes('poly') ||
    combinedContext.includes('factor') ||
    combinedContext.includes('代数') ||
    combinedContext.includes('方程')
  ) {
    inferredCategoryZh = '代数与方程';
    inferredCategoryEn = 'Algebra';
    inferredFormula = 'P(x) = ∑ aᵢ xⁱ';
    inferredIcon = '🔢';
  } else if (
    combinedContext.includes('stat') ||
    combinedContext.includes('prob') ||
    combinedContext.includes('mean') ||
    combinedContext.includes('variance') ||
    combinedContext.includes('统计') ||
    combinedContext.includes('概率')
  ) {
    inferredCategoryZh = '概率与统计';
    inferredCategoryEn = 'Statistics';
    inferredFormula = 'P(A|B) = P(B|A)P(A)/P(B)';
    inferredIcon = '📊';
  }

  const enName = capitalizedEnTokens.length > 0 ? `${capitalizedEnTokens.join(' ')} Calculator` : `${slug} Tool`;
  const zhKeywords = translatedZhTokens.length > 0 ? translatedZhTokens.join('') : cleanTokens.map((t) => t.toUpperCase()).join(' ');
  const zhName = zhKeywords ? `${zhKeywords}在线工具` : `${slug} 在线工具`;

  const descZh = customDesc || `专业在线${zhKeywords || slug}工具，提供即时数据交互与便捷功能支持。`;
  const descEn = customDesc || `Online ${enName} providing instant calculations and reliable web tools.`;

  const formulaFinal = site.formula && site.formula.trim().length > 0
    ? formatFormulaDisplay(site.formula)
    : inferredFormula;

  return {
    title: customTitle || (lang === 'zh' ? zhName : enName),
    formula: formulaFinal,
    category: customCategory || (lang === 'zh' ? inferredCategoryZh : inferredCategoryEn),
    desc: lang === 'zh' ? descZh : descEn,
    icon: customIcon || inferredIcon,
    tags: cleanTokens,
  };
}
