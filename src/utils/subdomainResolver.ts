/**
 * Universal Formula Formatter
 * Formats LaTeX strings into clean, beautiful Unicode math representations
 * so no raw backslashes or code syntax leaks onto the UI cards.
 */
export function formatFormulaDisplay(formula: string | undefined | null): string {
  if (!formula) return '';
  let str = String(formula).trim();
  if (!str) return '';

  // 1. cases environment
  str = str.replace(/\\begin\{cases\}([\s\S]*?)\\end\{cases\}/g, (_, inner) => {
    return inner.split(/\\\\/).map((s: string) => s.trim()).filter(Boolean).join(', ');
  });

  // 2. frac: simple fractions
  while (/\\frac\{([^{}]+)\}\{([^{}]+)\}/.test(str)) {
    str = str.replace(/\\frac\{([^{}]+)\}\{([^{}]+)\}/g, '$1/$2');
  }

  // 3. sqrt
  str = str.replace(/\\sqrt\{([^{}]+)\}/g, '√($1)');
  str = str.replace(/\\sqrt/g, '√');

  // 4. text / textrm / operatorname
  str = str.replace(/\\(?:text|mathrm|operatorname)\{([^{}]+)\}/g, '$1');

  // 5. greek and math symbols
  const symMap: Record<string, string> = {
    '\\rho': 'ρ',
    '\\pi': 'π',
    '\\theta': 'θ',
    '\\Delta': 'Δ',
    '\\pm': '±',
    '\\cdot': '·',
    '\\times': '×',
    '\\div': '÷',
    '\\neq': '≠',
    '\\leq': '≤',
    '\\geq': '≥',
    '\\approx': '≈',
    '\\infty': '∞',
    '\\rightarrow': '→',
    '\\gcd': 'gcd',
    '\\lcm': 'lcm',
    '\\quad': ' ',
    '\\,': ' ',
    '\\;': ' ',
    '\\!': '',
    '\\%': '%',
    '_1': '₁',
    '_2': '₂',
    '_0': '₀',
    '_i': 'ᵢ',
    '_n': 'ₙ',
    '{nt}': 'ⁿᵗ',
  };

  for (const [k, v] of Object.entries(symMap)) {
    str = str.split(k).join(v);
  }

  // Superscripts ^2, ^3, ^t
  str = str.replace(/\^2/g, '²').replace(/\^3/g, '³').replace(/\^t/g, 'ᵗ');

  // Clean remaining backslashes and braces
  str = str.replace(/\\/g, '').replace(/[{}]/g, '');
  str = str.replace(/\s+/g, ' ').trim();
  return str;
}

/**
 * Filter out Cloudflare Worker autogenerated uppercase dummy titles
 * e.g. 'COMPLETING THE SQUARE CALCULATOR', 'DENSITY CALCULATOR'
 */
export function isWorkerDummyTitle(title: string | undefined | null, slug: string): boolean {
  if (!title) return true;
  const t = title.trim();
  if (t.length === 0) return true;

  // Genuine Chinese titles are never dummy
  if (/[\u4e00-\u9fa5]/.test(t)) return false;

  // Rich site brand separators indicate user-curated project titles (e.g. 'RestStop Pro | ...')
  if (t.includes('|') || t.includes(' - ') || t.includes('：') || t.includes('—')) return false;

  const normalize = (s: string) =>
    s.toLowerCase().replace(/[-_]+/g, ' ').replace(/[^\w\s]/g, '').replace(/\s+/g, ' ').trim();
  const normTitle = normalize(t);
  const normSlug = normalize(slug);

  if (normTitle === normSlug) return true;

  const stripSuffixes = (s: string) =>
    s.replace(/\b(calculator|calculators|solver|solvers|tool|tools|online|kit|app|calc)\b/g, '').replace(/\s+/g, ' ').trim();

  if (stripSuffixes(normTitle) === stripSuffixes(normSlug)) return true;

  // All-caps ASCII English title matching worker pattern (e.g. 'COMPLETING THE SQUARE CALCULATOR')
  if (t === t.toUpperCase() && /^[A-Z0-9\s\-_]+$/.test(t)) return true;

  return false;
}

export function isWorkerDummyDesc(desc: string | undefined | null): boolean {
  if (!desc) return true;
  const d = desc.trim().toLowerCase();
  if (d.length < 5) return true;
  if (d === 'scientific calculation tool' || d === 'scientific calculation tools') return true;
  if (d.includes('scientific calculation tool')) return true;
  if (d.startsWith('online ') && d.endsWith(' calculator')) return true;
  return false;
}

export function isWorkerDummyCategory(cat: string | undefined | null): boolean {
  if (!cat) return true;
  const c = cat.trim().toLowerCase();
  return c === '' || c === 'tools' || c === 'tool' || c === 'calculator' || c === 'calculators' || c === 'general';
}

export function isWorkerDummyIcon(icon: string | undefined | null): boolean {
  if (!icon) return true;
  const i = icon.trim();
  return i === '' || i === '🧮' || i === '🌐';
}

